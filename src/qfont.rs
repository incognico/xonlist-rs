/// Strip `^N` / `^xRGB` color codes from a raw DarkPlaces string.
pub fn strip_colors(input: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(input.len());
    let mut i = 0;
    while i < input.len() {
        if input[i] == b'^' && i + 1 < input.len() {
            let next = input[i + 1];
            if next.is_ascii_digit() {
                i += 2;
                continue;
            }
            if next == b'x' && i + 4 < input.len() {
                let rgb = &input[i + 2..i + 5];
                if rgb.iter().all(|b| b.is_ascii_hexdigit()) {
                    i += 5;
                    continue;
                }
            }
        }
        out.push(input[i]);
        i += 1;
    }
    out
}

pub fn qfont_decode(s: &str) -> String {
    let mut chars = Vec::new();
    for c in s.chars() {
        if c == '\u{FFFD}' {
            continue;
        }
        if ('\u{E000}'..='\u{E0FF}').contains(&c) {
            let i = (c as u32 - 0xE000) as usize;
            chars.push(GLYPHS[i % GLYPHS.len()]);
        } else {
            chars.push(c);
        }
    }
    if chars.is_empty() {
        "unknown".to_string()
    } else {
        chars.into_iter().collect()
    }
}

/// Decode a raw server/player/map name: strip colors, UTF-8, qfont.
pub fn format_name(raw: &[u8]) -> String {
    let stripped = strip_colors(raw);
    let utf = String::from_utf8_lossy(&stripped);
    qfont_decode(&utf)
}

pub fn score2time(score: i32) -> String {
    if score == 0 {
        return "-".to_string();
    }
    let s = score.to_string();
    if s.len() <= 2 {
        format!("0.{s:0>2} sec.")
    } else {
        let (sec, cs) = s.split_at(s.len() - 2);
        format!("{sec}.{cs} sec.")
    }
}

pub fn ordinate(num: i32) -> String {
    let s = num.to_string();
    let suffix = if s.ends_with('1') && !s.ends_with("11") {
        "st"
    } else if s.ends_with('2') && !s.ends_with("12") {
        "nd"
    } else if s.ends_with('3') && !s.ends_with("13") {
        "rd"
    } else {
        "th"
    };
    format!("{num}{suffix}")
}

pub fn truncate_egc(s: &str, n: usize) -> String {
    use unicode_segmentation::UnicodeSegmentation;
    s.graphemes(true).take(n).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_len() {
        assert_eq!(GLYPHS.len(), 256);
    }

    #[test]
    fn strips_simple_colors() {
        assert_eq!(strip_colors(b"^1Red^7White"), b"RedWhite");
        assert_eq!(strip_colors(b"^xF00foo"), b"foo");
    }

    #[test]
    fn score_time() {
        assert_eq!(score2time(0), "-");
        assert_eq!(score2time(12345), "123.45 sec.");
        assert_eq!(score2time(5), "0.05 sec.");
    }

    #[test]
    fn ordinals() {
        assert_eq!(ordinate(1), "1st");
        assert_eq!(ordinate(11), "11th");
        assert_eq!(ordinate(21), "21st");
        assert_eq!(ordinate(2), "2nd");
        assert_eq!(ordinate(3), "3rd");
        assert_eq!(ordinate(4), "4th");
    }

    #[test]
    fn qfont_pua() {
        let s: String = "\u{E041}".into(); // 'A' in qfont lower bank
        assert_eq!(qfont_decode(&s), "A");
    }
}
